// Icone profil + Reglages (23/09, v548).
import { spawn } from 'child_process';
import { createRequire } from 'module';
const exiger = createRequire(new URL('../app-v2/package.json', import.meta.url));
const { chromium } = exiger('playwright');
const srv = spawn('python3',['-m','http.server','8080','--directory','app-v2/apercu/construit'],{stdio:'ignore',detached:true});
await new Promise(r=>setTimeout(r,1500));
let code=0; const ok=(c,m)=>{console.log((c?'✓ ':'✗ ')+m); if(!c) code=1;};
const nav = await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const page = await (await nav.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,locale:'fr-BE'})).newPage();
page.on('pageerror', e => { console.log('ERREUR JS', e.message); code=1; });
await page.goto('http://localhost:8080/app.html'); await page.waitForTimeout(1800);
await page.locator('[aria-label="Profil"]').first().tap(); await page.waitForTimeout(400);
const v = await page.locator('.profil-volet').innerText();
ok(!/Déconnexion|Se déconnecter/.test(v) && (await page.locator('.profil-volet .lang-choix').count()) === 0, 'volet sans langue ni deconnexion');
ok(/Recalculer mes besoins/.test(v) && /Mon compte/.test(v), 'volet : recalculer + mon compte');
await page.locator('.profil-volet button').filter({hasText:'Mon compte'}).tap(); await page.waitForTimeout(500);
ok(await page.locator('.rg-titre').innerText() === 'Paramètres du compte', 'Mon compte ouvre le compte');
ok(await page.locator('.rg-retour').count() === 0, 'un seul retour');
ok(!/••••/.test(await page.locator('.rg-corps').innerText()), 'plus de champs figes');
await page.locator('.j-retour').tap(); await page.waitForTimeout(400);
const menu = await page.locator('.rg-corps').innerText();
ok(!/Notifications/i.test(menu), 'notifications retirees');
ok(/Aide/i.test(menu), 'section Aide');
await page.locator('.rg-rangee').filter({hasText:"Gérer l'abonnement"}).tap(); await page.waitForTimeout(700);
await page.waitForTimeout(1500);
const abo = await page.locator('.rg-corps').innerText(); ok(/Statut/i.test(abo), 'page abonnement'); if (!/Statut/i.test(abo)) console.log(abo.slice(0,300));
await page.locator('.j-retour').tap(); await page.waitForTimeout(400);
await page.locator('.rg-deconnexion').tap(); await page.waitForTimeout(300);
ok(await page.locator('.rg-modale').count() === 1, 'deconnexion demande confirmation');
await page.locator('.rg-modale .rg-lien').tap(); await page.waitForTimeout(300);
ok(await page.locator('.rg-titre').count() === 1, 'annuler garde la session');
await nav.close(); try { process.kill(-srv.pid); } catch {} srv.kill(); process.exit(code);
